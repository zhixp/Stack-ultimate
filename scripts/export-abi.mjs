// Copies the compiled contract ABI into shared/ so the app and server can never drift from the contract.
// Run after `forge build` (npm run contracts:build does both).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const artifact = JSON.parse(readFileSync(`${root}contracts/out/StackUltimate.sol/StackUltimate.json`, 'utf8'));
const out = `// Generated by scripts/export-abi.mjs from contracts/src/StackUltimate.sol. Do not edit.\nexport const STACK_ULTIMATE_ABI = ${JSON.stringify(artifact.abi, null, 2)};\n`;
writeFileSync(`${root}shared/stackUltimateAbi.js`, out);
writeFileSync(`${root}shared/stackUltimateBytecode.json`, JSON.stringify({ bytecode: artifact.bytecode.object }));
console.log(`ABI exported (${artifact.abi.length} entries)`);
